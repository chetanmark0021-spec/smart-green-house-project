-- Additive schema for the GreenMind dashboard pages.
-- This does not change greenhouse telemetry, the alert webhook, or Brevo secrets.
-- Run once in Supabase SQL Editor after reviewing the table and public-read policies.

create table if not exists public.plants (
  id bigint generated by default as identity primary key,
  plant_name text not null,
  plant_type text not null,
  location text not null default '',
  planting_date date,
  created_at timestamptz not null default now()
);

create table if not exists public.plant_growth_logs (
  id bigint generated by default as identity primary key,
  plant_id bigint not null references public.plants(id) on delete cascade,
  measured_on date not null,
  height_cm numeric not null default 0,
  leaf_count integer not null default 0,
  growth_stage text,
  health_score numeric not null default 0,
  notes text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.plant_care_logs (
  id bigint generated by default as identity primary key,
  plant_id bigint not null references public.plants(id) on delete cascade,
  care_type text not null,
  amount numeric,
  unit text not null default '',
  notes text not null default '',
  performed_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists plant_growth_logs_plant_date_idx
  on public.plant_growth_logs (plant_id, measured_on desc);
create index if not exists plant_care_logs_plant_date_idx
  on public.plant_care_logs (plant_id, performed_at desc);

grant select on public.plants, public.plant_growth_logs, public.plant_care_logs
  to anon, authenticated;
grant all on public.plants, public.plant_growth_logs, public.plant_care_logs
  to service_role;

alter table public.plants enable row level security;
alter table public.plant_growth_logs enable row level security;
alter table public.plant_care_logs enable row level security;

drop policy if exists "public read plants" on public.plants;
create policy "public read plants" on public.plants
  for select to anon, authenticated using (true);
drop policy if exists "public read plant growth logs" on public.plant_growth_logs;
create policy "public read plant growth logs" on public.plant_growth_logs
  for select to anon, authenticated using (true);
drop policy if exists "public read plant care logs" on public.plant_care_logs;
create policy "public read plant care logs" on public.plant_care_logs
  for select to anon, authenticated using (true);

create table if not exists public.disease_analyses (
  id bigint generated by default as identity primary key,
  disease_name text not null,
  crop_name text,
  confidence_percent numeric,
  recommendation text,
  symptoms text,
  treatment text,
  organic_recommendations text,
  top_predictions jsonb not null default '[]'::jsonb,
  image_path text,
  original_filename text,
  model_name text,
  health_score numeric,
  health_label text,
  green_percent numeric,
  yellow_percent numeric,
  brown_percent numeric,
  visible_damage_percent numeric,
  sampled_pixels integer,
  created_at timestamptz not null default now()
);

alter table public.disease_analyses enable row level security;
drop policy if exists "public read disease analyses" on public.disease_analyses;
create policy "public read disease analyses" on public.disease_analyses
  for select to anon, authenticated using (true);
drop policy if exists "public create disease analyses" on public.disease_analyses;
create policy "public create disease analyses" on public.disease_analyses
  for insert to anon, authenticated with check (true);
grant select, insert on public.disease_analyses to anon, authenticated;
grant all on public.disease_analyses to service_role;

-- Private image storage. Dashboard uploads use the anonymous/ prefix.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('disease-images', 'disease-images', false, 10485760,
        array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do nothing;

drop policy if exists "public read disease analysis images" on storage.objects;
create policy "public read disease analysis images" on storage.objects
  for select to anon, authenticated using (bucket_id = 'disease-images');
drop policy if exists "public upload disease analysis images" on storage.objects;
create policy "public upload disease analysis images" on storage.objects
  for insert to anon, authenticated
  with check (bucket_id = 'disease-images' and name like 'anonymous/%');
